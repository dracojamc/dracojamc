=begin
Ruby se guia bajo el concepto PEMDAS (Paréntesis, Exponentes, Multiplicación y División, Adición y Sustracción) para determinar el orden de las operaciones. 
Esto significa que las operaciones dentro de los paréntesis se realizan primero, seguidas por exponentes, luego multiplicación y división (de izquierda a derecha), 
y finalmente adición y sustracción (de izquierda a derecha). 
=end
puts (2 + 3) * 4

puts 10 / 5
puts 10 / 3

puts 10.0 / 3
puts 10 / 3.0
puts 10.0 / 3.0

puts 10 % 3 #Este operador devuelve el residuo de la división de 10 entre 3, que es 1.